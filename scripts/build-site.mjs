// Prepares the website in site/: skin list and icons.
// Usage: npm run site   (download buttons point to the latest GitHub Release)
import { cpSync, readFileSync, writeFileSync } from "node:fs";

const SITE = "site";
const CASE_DATA = new Function(`${readFileSync("app/cases.js", "utf8")}; return CASE_DATA;`)();

const rand = (arr) => arr[Math.floor(Math.random() * arr.length)];
const sample = (arr, n) => [...arr].sort(() => Math.random() - 0.5).slice(0, n);
const skin = (rarity) => ([name, image]) => ({ name, image, rarity });
const byId = Object.fromEntries(CASE_DATA.map((c) => [c.id, c]));

// Floating / hover skins: mostly ★ knives and gloves, plus a few covert guns.
const knives = sample(byId["special-knives"].items.gold.map(skin("gold")), 16);
const gloves = byId["special-gloves"].items.gold.concat(byId["special-gloves"].items.red).map(skin("gold"));
const dopplers = sample(byId["special-doppler"].items.gold.map(skin("gold")), 8);
const coverts = CASE_DATA.filter((c) => !c.special).flatMap((c) => c.items.red.map(skin("red")));

// Reel: a mix of every rarity, like a real case spin.
const reel = [];
for (const c of CASE_DATA.filter((c) => !c.special)) {
  for (const r of ["blue", "purple", "pink", "red"]) reel.push(skin(r)(rand(c.items[r])));
}
reel.push(...sample(knives, 4), ...sample(gloves, 2));

const cases = CASE_DATA.map((c) => ({
  id: c.id,
  name: c.name,
  image: c.image,
  special: !!c.special,
  theme: c.theme,
  odds: c.odds,
  top: sample([...c.items.gold, ...c.items.red], 3).map(([name, image]) => ({ name, image })),
}));

const data = {
  knives,
  gloves: sample(gloves, 10),
  dopplers,
  coverts: sample(coverts, 10),
  reel: sample(reel, reel.length),
  cases,
  total: CASE_DATA.reduce((n, c) => n + Object.values(c.items).flat().length, 0),
};
writeFileSync(`${SITE}/skins.js`,
  `// Generated by scripts/build-site.mjs — do not edit by hand.\nconst SKINS = ${JSON.stringify(data)};\n`);

// Favicon.
cpSync("app/icons", `${SITE}/icons`, { recursive: true });

console.log(`site/ ready: ${knives.length + gloves.length + dopplers.length} hover skins, ${reel.length} reel items`);
