// ---------- spin ----------
let spinning = false;
let lastWin = null;
let auto = false;
let autoTimer;

function open() {
  const c = currentCase();
  if (spinning || state.balance < c.price) return;
  spinning = true;
  hideResult();

  // Commit immediately so closing the popup mid-spin never loses the drop.
  const win = roll(c);
  state.balance = round2(state.balance - c.price);
  state.inv.push(win);
  state.opened++;
  if (!state.best || win.value > state.best.value) state.best = win;
  save();
  renderTop();

  const reel = $("#reel");
  reel.innerHTML = "";
  const tiles = [];
  for (let i = 0; i < REEL_LEN; i++) {
    const t = tileEl(i === WIN_INDEX ? win : roll(c));
    tiles.push(t);
    reel.appendChild(t);
  }

  const viewW = $("#reel-wrap").clientWidth;
  const jitter = (Math.random() - 0.5) * (TILE - 16);
  const target = WIN_INDEX * TILE + 38 + jitter - viewW / 2;
  const duration = state.fast ? 500 : 3200;
  const t0 = performance.now();
  let lastIdx = -1;

  function frame(now) {
    const t = Math.min(1, (now - t0) / duration);
    const x = target * (1 - Math.pow(1 - t, 4));
    reel.style.transform = `translateX(${-x}px)`;
    const idx = Math.floor((x + viewW / 2) / TILE);
    if (idx !== lastIdx) { lastIdx = idx; if (!state.fast) tick(); }
    if (t < 1) return requestAnimationFrame(frame);
    finish(tiles[WIN_INDEX], win);
  }
  requestAnimationFrame(frame);
}

function finish(tile, win) {
  spinning = false;
  lastWin = win;
  const winTile = tileEl(win, false);
  winTile.classList.add("win");
  tile.replaceWith(winTile);

  const res = $("#result");
  res.style.setProperty("--rc", RARITIES[win.rarity].color);
  $("#result-name").textContent = win.name;
  $("#result-meta").textContent = `${win.label} · ${win.wear} · ${money(win.value)}`;
  $("#sell").textContent = `Vendre ${money(win.value)}`;
  res.classList.remove("hidden");
  updateStage();
  renderTop();

  if (isBigWin(win)) showReveal(win);
  else { fanfare(win.rarity); queueAuto(); }
}

// ---------- auto mode: keep opening until stopped or broke ----------
function setAuto(on) {
  auto = on && state.balance >= currentCase().price;
  clearTimeout(autoTimer);
  $("#auto").classList.toggle("on", auto);
  $("#auto").textContent = auto ? "Stop" : "Auto";
  if (auto && !spinning && $("#reveal").hidden) open();
}

function queueAuto() {
  if (!auto) return;
  clearTimeout(autoTimer);
  autoTimer = setTimeout(() => {
    if (state.balance < currentCase().price) return setAuto(false);
    open();
  }, state.fast ? 400 : 900);
}

