// Steam CDN serves resized images with a size suffix.
const steamImg = (url, size) => `${url}/${size}fx${size}f`;

let moneyFmt;
function money(n) {
  if (moneyFmt?.resolvedOptions().currency !== state.currency) {
    moneyFmt = new Intl.NumberFormat(CURRENCIES[state.currency], { style: "currency", currency: state.currency });
  }
  return moneyFmt.format(n);
}

function pickWeighted(entries) {
  const total = entries.reduce((s, [, w]) => s + w, 0);
  let r = Math.random() * total;
  for (const [key, w] of entries) {
    if ((r -= w) < 0) return key;
  }
  return entries[entries.length - 1][0];
}

// Stable 0..1 per skin name, so the same skin is always worth roughly the same.
function hash01(str) {
  let h = 2166136261;
  for (const ch of str) h = Math.imul(h ^ ch.charCodeAt(0), 16777619);
  return (h >>> 0) / 4294967296;
}

// ---------- rolling ----------
function roll(c) {
  const rarity = pickWeighted(Object.entries(c.odds || ODDS).filter(([r]) => c.items[r]?.length));
  const [name, image, factor = 1] = pick(c.items[rarity]);
  const wear = WEARS[pickWeighted(WEARS.map((w, i) => [i, w.p]))];
  const stattrak = Math.random() < 0.1;
  const base = c.mults ? c.price * c.mults[rarity] * factor
    : rarity === "gold" ? Math.max(c.price * 40, 80)
    : c.price * RARITIES[rarity].mult;
  const value = base * (0.6 + hash01(name) * 1.2) * wear.mult * (stattrak ? 1.5 : 1);
  return {
    id: Date.now().toString(36) + Math.random().toString(36).slice(2, 6),
    rarity,
    image,
    wear: wear.label,
    value: Math.max(0.01, round2(value)),
    label: c.special ? SPECIAL_LABELS[rarity] : RARITIES[rarity].label,
    name: stattrak ? name.replace(/^(★ )?/, "$1StatTrak™ ") : name,
  };
}

// ---------- audio ----------
let audio;
function beep(freq, { type = "square", gain = 0.04, length = 0.05, delay = 0 } = {}) {
  if (!state.sound) return;
  try {
    audio ||= new AudioContext();
    const t = audio.currentTime + delay;
    const o = audio.createOscillator();
    const g = audio.createGain();
    o.type = type;
    o.frequency.value = freq;
    g.gain.setValueAtTime(gain, t);
    g.gain.exponentialRampToValueAtTime(0.0001, t + length);
    o.connect(g).connect(audio.destination);
    o.start(t);
    o.stop(t + length + 0.01);
  } catch {}
}
const tick = () => beep(900);
function fanfare(rarity) {
  const n = RARITY_ORDER.indexOf(rarity);
  for (let i = 0; i <= n; i++) beep(900 * (1 + i * 0.25), { delay: i * 0.07 });
}
function bigFanfare(rarity) {
  const notes = rarity === "gold" ? [523, 659, 784, 1047, 1319, 1568] : [440, 554, 659, 880];
  notes.forEach((f, i) => beep(f, { type: "triangle", gain: 0.08, length: 0.35, delay: i * 0.11 }));
  beep(notes.at(-1), { type: "triangle", gain: 0.06, length: 1.2, delay: notes.length * 0.11 });
}

